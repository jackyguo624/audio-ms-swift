#!/usr/bin/env bash
# Fetch only the upstream speech encoder/adapter implementation; no model weights.
set -euo pipefail

if [[ ${1:-} == -h || ${1:-} == --help ]]; then
    cat <<'USAGE'
Usage: bash prepare_source.sh [destination]
Or set FIRERED_ASR_REPO. The default is PROJECT_ROOT/.vendor/FireRedASR.
Fetches the pinned official source checkout without model weights.
USAGE
    exit 0
fi

revision=834635e4cf277ed8ca92049fc375b17c3dc20748
url=https://github.com/FireRedTeam/FireRedASR.git
project_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
destination=${FIRERED_ASR_REPO:-${project_root}/.vendor/FireRedASR}
if [[ $# -gt 1 ]]; then
    echo 'Usage: bash prepare_source.sh [destination]' >&2
    exit 2
fi
destination=${1:-$destination}

if [[ -e "$destination" ]]; then
    if [[ ! -d "$destination/.git" ]] || [[ ! -d "$destination/fireredasr" ]]; then
        echo "Refusing to replace an existing non-FireRed checkout: $destination" >&2
        exit 1
    fi
    remote=$(git -C "$destination" remote get-url origin)
    case "$remote" in
        https://github.com/FireRedTeam/FireRedASR|https://github.com/FireRedTeam/FireRedASR.git|git@github.com:FireRedTeam/FireRedASR.git) ;;
        *) echo "Refusing to modify a checkout with a different origin: $destination" >&2; exit 1 ;;
    esac
    # Importing upstream creates Python caches because it has no .gitignore.
    # Ignore only generated bytecode; preserve every real source/data change.
    if [[ -n "$(git -C "$destination" status --porcelain --untracked-files=all -- . \
        ':(exclude)**/__pycache__/**' ':(exclude)**/*.pyc' ':(exclude)**/*.pyo')" ]]; then
        echo "Refusing to modify a dirty checkout: $destination" >&2
        exit 1
    fi
    current=$(git -C "$destination" rev-parse HEAD)
    if [[ "$current" != "$revision" ]]; then
        echo "Existing checkout has a different revision ($current); choose a new destination." >&2
        exit 1
    fi
else
    mkdir -p -- "$(dirname -- "$destination")"
    temporary=$(mktemp -d "$(dirname -- "$destination")/.firered-download.XXXXXX")
    trap 'rm -rf -- "$temporary"' EXIT
    git clone --no-checkout -- "$url" "$temporary"
    git -C "$temporary" checkout --detach "$revision"
    mv --no-clobber --no-target-directory -- "$temporary" "$destination"
    if [[ -d "$temporary" ]]; then
        echo "Destination appeared during download; refusing to overwrite it: $destination" >&2
        exit 1
    fi
    trap - EXIT
fi
printf 'FireRedASR source ready at %s\n' "$destination"
printf 'Set FIRERED_ASR_REPO to this absolute directory when training outside the project root.\n'
